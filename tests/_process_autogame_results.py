# The purpose of this script is to:
# Load the .jsonl file from `_run_and_save_autogames.py` and extract the results.

# Disclaimer: most of this file is generated by AI.

import pandas as pd
from pathlib import Path


def print_test_summary(test_results_folder_path: Path, test_file_name: str):

    TEST_FILE_PATH = test_results_folder_path / rf"{test_file_name}"

    try:
        df = pd.read_json(TEST_FILE_PATH, lines=True)
    except FileNotFoundError:
        print(f"\nSkipping `{test_file_name}`... (file not found)\n")
        return

    comparison_rows = []

    for match_id, match_df in df.groupby("match_id"):

        try:
            #  `match_df["name"] == "Yellow-Fish"` indexing -> yields pd.Series: [(row_0_id, True), (row_1_id, False)]
            fishbot_player_name = [player_id for player_id in match_df["name"] if "Fis" in player_id][0]
            fishbot_row = match_df[match_df['name'] == fishbot_player_name].iloc[0]
        except IndexError:
            print(f"\nCould not find 'Fis'. Skipping...\n")
            return

        try:
            opponent_player_name = [player_id for player_id in match_df["name"] if "Fis" not in player_id][0]
            opponent_row = match_df[match_df['name'] == opponent_player_name].iloc[0]
        except IndexError:
            print(f"\nCould not find a non-FishBot player. Skipping...\n")
            return

        fishbot_win = not fishbot_row["defeated"]

        kd_ratio = (
                fishbot_row["units_killed"] /
                max(opponent_row["units_killed"], 1)
        )

        extract_ratio = (
                fishbot_row["extract_power"] /
                max(opponent_row["extract_power"], 1)
        )

        comparison_rows.append({
            "match_id": match_id,
            "opponent_row": opponent_row["name"],
            "fishbot_win": fishbot_win,
            "kd_ratio": kd_ratio,
            "extract_ratio": extract_ratio,
        })

    comparison_df = pd.DataFrame(comparison_rows)

    win_rate = comparison_df["fishbot_win"].mean()
    avg_kd = comparison_df["kd_ratio"].mean()
    avg_extract = comparison_df["extract_ratio"].mean()

    round_to_2dp = lambda x: round(x, 2)

    ## Print results summary
    print(f'\nAnalysed "{test_file_name}"\n')

    print(f"Win rate: {round_to_2dp(win_rate * 100)}% ({len(comparison_df['fishbot_win'])} games)")
    print(f"Average kd ratio: {round_to_2dp(avg_kd)}")
    print(f"Average oil ratio: {round_to_2dp(avg_extract)}")


