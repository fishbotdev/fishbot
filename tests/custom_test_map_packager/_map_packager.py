def parse_map_folder_name(source_dir: Path) -> dict:
    """
    Validate a source map directory and extract metadata.

    Parameters
    ----------
    source_dir : Path

    Returns
    -------
    dict

    Raises
    ------
    ValueError
        If the directory name or contents are invalid.
    """

    if not source_dir.is_dir():
        raise ValueError(f"'{source_dir}' is not a directory.")

    # Parse folder name.
    match = re.fullmatch(r"(\d+)c-(.+)", source_dir.name)
    if match is None:
        raise ValueError(
            f"Folder name '{source_dir.name}' does not match '<players>c-<name>'."
        )

    source_players = int(match.group(1))
    base_name = match.group(2)

    # Validate directory contents.
    expected_files = {
        "game.map",
        "ttypes.ttp",
        "feature.json",
        "struct.json",
        "droid.json",
    }

    actual_files = {
        p.name
        for p in source_dir.iterdir()
        if p.is_file()
    }

    if actual_files != expected_files:
        missing = expected_files - actual_files
        extra = actual_files - expected_files

        messages = []

        if missing:
            messages.append(
                f"missing: {', '.join(sorted(missing))}"
            )

            raise ValueError(
                f"Invalid contents for '{source_dir.name}' ({'; '.join(messages)})."
            )

        if extra:
            messages.append(
                f"unexpected: {', '.join(sorted(extra))}"
            )

    return {
        "source_name": source_dir.name,
        "base_name": base_name,
        "source_players": source_players,
        "output_name": f"{source_players + 1}c-{base_name}",
    }


def parse_game_map(path: Path) -> tuple[int, int]:
    """
    Extract map dimensions from game.map.
    """

    with open(path, "rb") as f:
        header = f.read(16)

    if len(header) != 16:
        raise ValueError("game.map header is too short")

    magic = header[:4]

    if magic != b"map ":
        raise ValueError(
            f"Unexpected game.map header: {magic}"
        )

    version, width, height = struct.unpack(
        "<III",
        header[4:16],
    )

    return width, height


def copy_static_assets(source_dir: Path, build_dir: Path) -> None:
    """Copy assets that are not modified."""

    for filename in (
        "game.map",
        "ttypes.ttp",
        "feature.json",
    ):
        shutil.copy2(
            source_dir / filename,
            build_dir / filename,
        )


def duplicate_start_position(
    data: dict,
    source_startpos: int,
    new_startpos: int,
    key_prefix: str,
) -> None:
    """
    Duplicate / relabel all entries belonging to one start position.
    """

    next_id = 8888

    for item in list(data.values()):
        if item.get("startpos") != source_startpos:
            continue

        if item.get("name") == "A0CommandCentre":
            # this sets the start position
            new_item = copy.deepcopy(item)
            new_item["start_pos"] = new_startpos
            
            data[f"{key_prefix}_{next_id:04d}"] = new_item

            next_id += 1

        # Else, overwrite the startpos to prevent a conflict
        item["startpos"] = new_startpos

def translate_start_position(
    data: dict,
    startpos: int,
    dx: int,
    dy: int,
) -> None:
    """
    Translate all structures belonging to a start position.
    """

    for structure in data.values():
        if structure.get("startpos") != startpos:
            continue

        structure["position"][0] += dx
        structure["position"][1] += dy


def process_struct_json(src: Path, dst: Path, metadata: dict) -> None:
    data = read_json(src)

    new_player_id = metadata["source_players"]

    duplicate_start_position(
        data,
        source_startpos=0,
        new_startpos=new_player_id,
        key_prefix="structure",
    )

    translate_start_position(
        data,
        startpos=0,
        dx=POSITION_OFFSET,
        dy=POSITION_OFFSET,
    )

    write_json(dst, data)


