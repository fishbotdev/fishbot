def package_map(
    build_dir: Path,
    metadata: dict,
    output_dir: Path,
) -> Path:
    """
    Package a build directory into a .wz archive.

    Parameters
    ----------
    build_dir : Path
        Temporary directory containing the completed map.
    metadata : dict
        Map metadata returned by parse_map_folder_name().
    output_dir : Path
        Destination directory for the archive.

    Returns
    -------
    Path
        Path to the generated archive.

    Raises
    ------
    ValueError
        If packaging fails.
    """

    output_path = output_dir / f"{metadata['output_name']}.wz"

    try:
        with zipfile.ZipFile(
            output_path,
            mode="w",
            compression=zipfile.ZIP_DEFLATED,
        ) as archive:

            for file in build_dir.iterdir():
                if file.is_file():
                    archive.write(
                        file,
                        arcname=file.name,
                    )

    except Exception as e:
        raise ValueError(f"Failed to package map: {e}")

    return output_path


def repackage_map(
    source_dir: Path,
    output_dir: Path,
) -> str:
    """
    Process a single source map.

    Parameters
    ----------
    source_dir : Path
        Source map directory.
    output_dir : Path
        Directory where the generated .wz archive will be written.

    Returns
    -------
    str
        Name of the generated archive.

    Raises
    ------
    ValueError
        If any processing step fails.
    """

    output_dir.mkdir(parents=True, exist_ok=True)

    metadata = parse_map_folder_name(source_dir)

    map_width, map_height = parse_game_map(
        source_dir / "game.map"
    )

    metadata["map_width"] = map_width
    metadata["map_height"] = map_height
    metadata["tileset"] = __tp.parse_tileset_from_lev(
        addon_lev_path=WZ2100_ADDON_LEV_FILEPATH,
        map_folder_name=source_dir.name,
    )

    with tempfile.TemporaryDirectory() as temp_dir:
        build_dir = Path(temp_dir)

        # Copy static assets.
        copy_static_assets(source_dir, build_dir)

        # Process transformable assets.
        process_struct_json(
            source_dir / "struct.json",
            build_dir / "struct.json",
            metadata,
        )

        process_droid_json(
            source_dir / "droid.json",
            build_dir / "droid.json",
            metadata,
        )

        # Generate metadata files.
        generate_metadata(build_dir, metadata)

        # Package the finished map.
        output_path = package_map(
            build_dir,
            metadata,
            output_dir,
        )

    return output_path.name



