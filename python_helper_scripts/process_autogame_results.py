# The purpose of this script is to:
# Load the .jsonl file from `run_and_save_autogames.py` and extract the results.

# Disclaimer: most of this file is generated by AI.



######## PROGRAM CONFIGURATION ########

FILE_NAME = rf"""
c6bf1b5,GAMMA_INSANE_COBRA_T2,50G.jsonl
"""

######## END PROGRAM CONFIGURATION ########
FILE_NAME = FILE_NAME.lstrip().rstrip()

import pandas as pd

df = pd.read_json(FILE_NAME, lines=True)

comparison_rows = []

for match_id, match_df in df.groupby("match_id"):

    yellow = match_df[match_df["name"] == "Yellow-Fish"].iloc[0]
    opponent = match_df[match_df["name"] != "Yellow-Fish"].iloc[0]

    yellow_win = not yellow["defeated"]

    kd_ratio = (
        yellow["units_killed"] /
        max(opponent["units_killed"], 1)
    )

    extract_ratio = (
        yellow["extract_power"] /
        max(opponent["extract_power"], 1)
    )

    comparison_rows.append({
        "match_id": match_id,
        "opponent": opponent["name"],
        "yellow_win": yellow_win,
        "kd_ratio": kd_ratio,
        "extract_ratio": extract_ratio,
    })

comparison_df = pd.DataFrame(comparison_rows)

win_rate = comparison_df["yellow_win"].mean()
avg_kd = comparison_df["kd_ratio"].mean()
avg_extract = comparison_df["extract_ratio"].mean()

round_to_2dp = lambda x: round(x, 2)

## Print results summary
print(f'\nAnalysed "{FILE_NAME}"\n')

print(f"Win rate: {round_to_2dp(win_rate * 100)}")
print(f"Average kd ratio: {round_to_2dp(avg_kd)}")
print(f"Average oil ratio: {round_to_2dp(avg_extract)}")
