def extract_runC2(filepath: str, function_name: str = "runC2") -> pd.DataFrame:
    columns = [
        "calls",
        "avg_usec",
        "worst_usec",
        "worst_call_at",
        "ge_limit",
        "ge_limit_half",
        "function",
    ]

    rows = []

    with open(filepath, "r") as f:
        for line in f:
            # find the target row
            if function_name in line:
                # split table columns
                parts = [p.strip() for p in line.split("|")]

                # defensive check (expected 7 columns)
                if len(parts) != 7:
                    continue

                rows.append({
                    "calls": int(parts[0]),
                    "avg_usec": int(parts[1]),
                    "worst_usec": int(parts[2]),
                    "worst_call_at": int(parts[3]),
                    "ge_limit": int(parts[4]),
                    "ge_limit_half": int(parts[5]),
                    "function": parts[6],
                })

    return pd.DataFrame(rows, columns=columns)

